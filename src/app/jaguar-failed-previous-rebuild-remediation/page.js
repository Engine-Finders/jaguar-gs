import AuthorityPage from "@/components/shared/AuthorityPage";
import JsonLd from "@/components/shared/JsonLd";
import { serviceSchema, faqSchema, breadcrumbSchema, graphDoc } from "@/lib/schema";
import data from "@/data/authority/jaguar-failed-previous-rebuild-remediation.json";

const PATH = "/jaguar-failed-previous-rebuild-remediation";
const FAQ = (data.sections || []).filter((s) => s.kind === "faq").flatMap((s) => s.items || []);

export const metadata = {
  title: "Jaguar Failed Previous Rebuild Remediation | Jaguar Garage",
  description: "Professional assessment and correction of poorly-rebuilt Jaguar engines. We strip, inspect, and re-do work from other workshops to get your engine right.",
  alternates: { canonical: PATH },
};

export default function JaguarFailedPreviousRebuildRemediationPage() {
  return (
    <>
      <JsonLd
        data={graphDoc([
          serviceSchema({ name: data.h1, description: data.metaDescription, path: PATH }),
          faqSchema(FAQ, PATH),
          breadcrumbSchema(
            [{ name: "Home", path: "/" }, { name: "Guides", path: "/guides" }, { name: data.h1, path: PATH }],
            PATH
          ),
        ])}
      />
      <AuthorityPage data={data} />
    </>
  );
}
