import AuthorityPage from "@/components/shared/AuthorityPage";
import JsonLd from "@/components/shared/JsonLd";
import { serviceSchema, faqSchema, breadcrumbSchema, graphDoc } from "@/lib/schema";
import data from "@/data/authority/jaguar-cylinder-head-repair-rebuild.json";

const PATH = "/jaguar-cylinder-head-repair-rebuild";
const FAQ = (data.sections || []).filter((s) => s.kind === "faq").flatMap((s) => s.items || []);

export const metadata = {
  title: "Jaguar Cylinder Head Repair & Rebuild | Jaguar Garage",
  description: "Professional Jaguar cylinder head repair and rebuild: machining, valve work, pressure testing, and reassembly. Fixed-price quotes, 12-month warranty.",
  alternates: { canonical: PATH },
};

export default function JaguarCylinderHeadRepairRebuildPage() {
  return (
    <>
      <JsonLd
        data={graphDoc([
          serviceSchema({ name: data.h1, description: data.metaDescription, path: PATH }),
          faqSchema(FAQ, PATH),
          breadcrumbSchema(
            [{ name: "Home", path: "/" }, { name: "Guides", path: "/guides" }, { name: data.h1, path: PATH }],
            PATH
          ),
        ])}
      />
      <AuthorityPage data={data} />
    </>
  );
}
