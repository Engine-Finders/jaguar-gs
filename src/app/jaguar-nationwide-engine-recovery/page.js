import AuthorityPage from "@/components/shared/AuthorityPage";
import JsonLd from "@/components/shared/JsonLd";
import { serviceSchema, faqSchema, breadcrumbSchema, graphDoc } from "@/lib/schema";
import data from "@/data/authority/jaguar-nationwide-engine-recovery.json";

const PATH = "/jaguar-nationwide-engine-recovery";
const FAQ = (data.sections || []).filter((s) => s.kind === "faq").flatMap((s) => s.items || []);

export const metadata = {
  title: "Jaguar Nationwide Engine Recovery | Jaguar Garage",
  description: "Jaguar engine recovery service covering the UK. Flatbed transport, secure collection, and delivery to our Essex workshop. Get a quote for nationwide recovery today.",
  alternates: { canonical: PATH },
};

export default function JaguarNationwideEngineRecoveryPage() {
  return (
    <>
      <JsonLd
        data={graphDoc([
          serviceSchema({ name: data.h1, description: data.metaDescription, path: PATH }),
          faqSchema(FAQ, PATH),
          breadcrumbSchema(
            [{ name: "Home", path: "/" }, { name: "Guides", path: "/guides" }, { name: data.h1, path: PATH }],
            PATH
          ),
        ])}
      />
      <AuthorityPage data={data} />
    </>
  );
}
